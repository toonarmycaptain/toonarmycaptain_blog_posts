"""
Build the blog's header and footer from toonarmycaptain_website's master branch.

Fetches the website's master into .cache/, has its Flask app render base.html, cuts out the nav and
footer, rewrites their links for the blog, and writes them as Zensical partial overrides. The
static files they use, and header_footer.css, are copied into the blog's docs.

    uv run python scripts/generate_header_footer.py

To try uncommitted changes to the website's header or footer, use a local checkout instead:

    uv run python scripts/generate_header_footer.py --website ../toonarmycaptain_website

The render runs in the website's own environment, built by uv from its lockfile.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

WEBSITE_REPO = 'https://github.com/toonarmycaptain/toonarmycaptain_website.git'
WEBSITE_BRANCH = 'master'
MAIN_SITE = 'https://toonarmycaptain.com'

BLOG_ROOT = Path(__file__).resolve().parent.parent
WEBSITE_CACHE = BLOG_ROOT / '.cache' / 'toonarmycaptain_website'
PARTIALS_DIR = BLOG_ROOT / 'overrides' / 'partials'
SHARED_DIR = BLOG_ROOT / 'docs' / 'shared'
SHARED_URL = '/shared/'
# Linked from the website's <head>, so not found by scanning the nav and footer.
EXTRA_STATIC_FILES = ('header_footer.css', 'favicon.ico')

GENERATED_NOTE = '{#- Generated by scripts/generate_header_footer.py from toonarmycaptain_website. Do not edit. -#}\n'

# Zensical's drawer (for the sidebar on narrow screens) and search controls, added to the nav.
BLOG_CONTROLS = '''\
            <li class="blog_controls">
                <label class="blog_control blog_control--drawer md-icon" for="__drawer" aria-label="{{ lang.t('nav') }}">
                    {% include ".icons/" ~ (config.theme.icon.menu or "material/menu") ~ ".svg" %}
                </label>
                <label class="blog_control blog_control--search md-icon" for="__search" aria-label="{{ lang.t('search') }}">
                    {% include ".icons/" ~ (config.theme.icon.search or "material/magnify") ~ ".svg" %}
                </label>
                {% include "partials/search.html" %}
            </li>
'''


# --- Run in this repo's environment ------------------------------------------------------------

def fetch_website() -> Path:
    """Clone or update the website's master branch in .cache/, and return its path."""
    git = ['git', '-C', str(WEBSITE_CACHE)]
    if (WEBSITE_CACHE / '.git').is_dir():
        subprocess.run(git + ['fetch', '--quiet', '--depth', '1', 'origin', WEBSITE_BRANCH], check=True)
        subprocess.run(git + ['reset', '--quiet', '--hard', 'FETCH_HEAD'], check=True)
        subprocess.run(git + ['clean', '--quiet', '-ffdx', '--exclude', '.venv'], check=True)
    else:
        WEBSITE_CACHE.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(['git', 'clone', '--quiet', '--depth', '1', '--branch', WEBSITE_BRANCH,
                        WEBSITE_REPO, str(WEBSITE_CACHE)], check=True)
    commit = subprocess.run(git + ['log', '-1', '--format=%h %s'], check=True, capture_output=True, text=True)
    print(f'Website {WEBSITE_BRANCH}: {commit.stdout.strip()}', flush=True)
    return WEBSITE_CACHE


def render_in_website_env(website_dir: Path) -> None:
    """Rerun this script with --render, in the website's environment."""
    if not (website_dir / 'uv.lock').is_file():
        raise SystemExit(f'{website_dir} has no uv.lock, so uv can\'t build its environment.')
    env ={key: value for key, value in os.environ.items() if key != 'VIRTUAL_ENV'}  # This repo's.
    subprocess.run(['uv', 'run', '--quiet', '--frozen', '--project', str(website_dir),
                    'python', __file__, '--render', str(website_dir)], check=True, env=env)


# --- Run in the website's environment ----------------------------------------------------------

def render_base(website_dir: Path) -> tuple[str, str, Path]:
    """
    Render the website's base.html as if at /blog/, with the website's test config.

    :param website_dir: Path to a toonarmycaptain_website checkout.
    :return: The rendered page, the app's BLOG_URL, and its static folder.
    """
    sys.path.insert(0, str(website_dir))
    from flask import render_template
    from tests.test_app_fixture import app_with_test_config

    with tempfile.TemporaryDirectory() as db_dir:  # The app creates its contact db on startup.
        app = app_with_test_config(Path(db_dir))
        with app.test_request_context('/blog/'):
            return render_template('base.html'), app.config['BLOG_URL'], Path(app.static_folder)


def cut(html: str, tag: str, css_class: str) -> str:
    """Return the one <tag class="css_class">...</tag> element in html."""
    matches = re.findall(rf'<{tag} class="{css_class}">.*?</{tag}>', html, re.DOTALL)
    if len(matches) != 1:
        raise SystemExit(f'Expected one <{tag} class="{css_class}">, found {len(matches)}.')
    return matches[0]


def rewrite_links(html: str, static_files: set[str]) -> str:
    """
    Point root-relative links at the main site, and /static/ files at the blog's copies.

    :param static_files: Collects the names of the static files referenced.
    """
    def rewrite(match: re.Match) -> str:
        attribute, path = match.groups()
        if path.startswith('/static/'):
            name = path.removeprefix('/static/')
            static_files.add(name)
            return f'{attribute}="{SHARED_URL}{name}"'
        return f'{attribute}="{MAIN_SITE}{path}"'

    return re.sub(r'\b(href|src)="(/(?!/)[^"]*)"', rewrite, html)


def mark_blog_active(nav: str, blog_url: str) -> str:
    """Make the nav's Blog link the active page, at the blog's root, in the same tab."""
    def activate(match: re.Match) -> str:
        tag = match.group(0)
        tag = re.sub(r'\bclass="([^"]*)"', r'class="\1 nav_active_page "', tag)
        tag = re.sub(r'\s(target|rel)="[^"]*"', '', tag)
        return tag.replace(f'href="{blog_url}"', 'href="/"')

    nav, count = re.subn(rf'<a\b[^>]*\bhref="{re.escape(blog_url)}"[^>]*>', activate, nav)
    if count != 1:
        raise SystemExit(f'Expected one nav link to BLOG_URL {blog_url!r}, found {count}.')
    return nav


def raw(html: str) -> str:
    """Wrap rendered HTML so Zensical's Jinja leaves it alone."""
    return '{% raw %}' + html + '{% endraw %}'


def render(website_dir: Path) -> None:
    html, blog_url, static_folder = render_base(website_dir)
    static_files = set(EXTRA_STATIC_FILES)

    nav = mark_blog_active(rewrite_links(cut(html, 'nav', 'top_navbar'), static_files), blog_url)
    footer = rewrite_links(cut(html, 'footer', 'footer'), static_files)

    missing = sorted(name for name in static_files if not (static_folder / name).is_file())
    if missing:
        raise SystemExit(f'Missing from the website\'s static folder: {", ".join(missing)}')

    nav_start, nav_end = nav.rsplit('</ul>', 1)
    header = (GENERATED_NOTE
              + '<header class="site_header" data-md-component="header">\n'  # Zensical's JS needs this.
              + raw(nav_start) + '\n' + BLOG_CONTROLS + raw('</ul>' + nav_end) + '\n'
              + '</header>\n')

    PARTIALS_DIR.mkdir(parents=True, exist_ok=True)
    (PARTIALS_DIR / 'header.html').write_text(header)
    (PARTIALS_DIR / 'footer.html').write_text(GENERATED_NOTE + raw(footer) + '\n')

    shutil.rmtree(SHARED_DIR, ignore_errors=True)
    SHARED_DIR.mkdir(parents=True)
    for name in sorted(static_files):
        shutil.copy2(static_folder / name, SHARED_DIR / name)
    print(f'Wrote header and footer partials, and copied {len(static_files)} files to {SHARED_DIR}.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--website', type=Path,
                        help=f'a local toonarmycaptain_website checkout to use instead of {WEBSITE_BRANCH}')
    parser.add_argument('--render', type=Path, help=argparse.SUPPRESS)  # Internal: the second stage.
    args = parser.parse_args()
    if args.render:
        render(args.render.resolve())
    else:
        render_in_website_env(args.website.resolve() if args.website else fetch_website())
